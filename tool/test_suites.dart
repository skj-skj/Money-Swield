// Writes `test_suites/`: every test file of `test/` in two suite files, for
// full runs (`make test`). Run from the project root:
//
//   dart tool/test_suites.dart
//
// (Plain `dart`, not `dart run`: that also runs the package build hooks,
// which compile the test SQLite.)
//
// Why: `flutter test test/` compiles and starts each of the ~85 test files
// on its own, 5–22 s each, two at a time on this machine; that start-up was
// as long as the tests themselves (823 s against 816 s, measured
// 2026-10-07). Two suites are compiled twice in all, and run side by side.
//
// Files with a `testWidgets` go in `widgets_test.dart`, the others in
// `logic_test.dart`: about the same test time each (≈ 400 s, measured).
// Each test file runs in its own `group`, named by its path, so a failure
// still says which file it came from. Single files still run as before
// (`flutter test test/…`, `make test FILES=…`).
//
// The output is generated: don't edit it, it is git-ignored. Each suite
// also checks that it still lists every test file, so a suite left over
// from before a test file was added fails instead of skipping it.
import 'dart:io';

const _outputFolder = 'test_suites';

void main() {
  final files = [
    for (final entity in Directory('test').listSync(recursive: true))
      if (entity is File && entity.path.endsWith('_test.dart'))
        entity.path.replaceAll(r'\', '/'),
  ]..sort();
  final widgets = [
    for (final file in files)
      if (File(file).readAsStringSync().contains('testWidgets(')) file,
  ];
  final logic = [
    for (final file in files)
      if (!widgets.contains(file)) file,
  ];

  final folder = Directory(_outputFolder);
  if (folder.existsSync()) folder.deleteSync(recursive: true);
  folder.createSync();
  _writeSuite('logic', logic, all: files);
  _writeSuite('widgets', widgets, all: files);
  stdout.writeln(
    'test_suites: ${logic.length} logic + ${widgets.length} widget test '
    'files',
  );
}

void _writeSuite(String name, List<String> files, {required List<String> all}) {
  final out = StringBuffer()
    ..writeln('// GENERATED by tool/test_suites.dart. Do not edit.')
    ..writeln("import 'dart:io';")
    ..writeln()
    ..writeln("import 'package:flutter_test/flutter_test.dart';")
    ..writeln();
  for (final (i, file) in files.indexed) {
    out.writeln("import '../$file' as t$i;");
  }
  out
    ..writeln()
    ..writeln('/// Every test file of `test/` when this was generated.')
    ..writeln('const _allTestFiles = [');
  for (final file in all) {
    out.writeln("  '$file',");
  }
  out
    ..writeln('];')
    ..writeln()
    ..writeln('void main() {')
    ..writeln(
      "  test('the suites list every test file (else run "
      "dart tool/test_suites.dart)', () {",
    )
    ..writeln('    final now = [')
    ..writeln(
      "      for (final f in Directory('test').listSync(recursive: true))",
    )
    ..writeln("        if (f is File && f.path.endsWith('_test.dart'))")
    ..writeln(r"          f.path.replaceAll(r'\', '/'),")
    ..writeln('    ]..sort();')
    ..writeln('    expect(now, _allTestFiles);')
    ..writeln('  });');
  for (final (i, file) in files.indexed) {
    out.writeln("  group('${file.substring('test/'.length)}', t$i.main);");
  }
  out.writeln('}');
  File('$_outputFolder/${name}_test.dart').writeAsStringSync(out.toString());
}
