// Development tool: creates a new, empty migration. Not part of the app.
//
// Usage (from the project root):
//   dart tool/new_migration.dart add_currency_to_expenses
//
// Creates lib/data/services/database/migrations/<unix time>_<name>.dart and
// regenerates all_migrations.dart so the app runs it.

import 'dart:io';

final _migrationsFolder = Directory.fromUri(
  Platform.script.resolve('../lib/data/services/database/migrations/'),
);
final _namePattern = RegExp(r'^[a-z][a-z0-9_]*$');
final _fileNamePattern = RegExp(r'^(\d+)_([a-z][a-z0-9_]*)\.dart$');

void main(List<String> arguments) {
  if (arguments.length != 1 || !_namePattern.hasMatch(arguments.single)) {
    stderr.writeln('Usage: dart tool/new_migration.dart <snake_case_name>');
    stderr.writeln('Example: dart tool/new_migration.dart add_currency_to_expenses');
    exitCode = 64; // Usage error.
    return;
  }
  final name = arguments.single;
  final existing = _migrationFiles();

  if (existing.any((m) => m.name == name)) {
    stderr.writeln('A migration named "$name" already exists. Pick a different name.');
    exitCode = 1;
    return;
  }

  // Unix time in seconds, bumped if another migration already uses it.
  var version = DateTime.now().millisecondsSinceEpoch ~/ 1000;
  for (final m in existing) {
    if (m.version >= version) version = m.version + 1;
  }

  final file = File.fromUri(_migrationsFolder.uri.resolve('${version}_$name.dart'));
  file.writeAsStringSync(_migrationTemplate(version, name));
  _writeRegistry([...existing, (version: version, name: name, fileName: '${version}_$name.dart')]);

  stdout.writeln('Created ${_relative(file.path)}');
  stdout.writeln('Class:   ${_className(name)}');
}

typedef _MigrationFile = ({int version, String name, String fileName});

List<_MigrationFile> _migrationFiles() {
  final files = <_MigrationFile>[];
  for (final entity in _migrationsFolder.listSync()) {
    final fileName = entity.uri.pathSegments.last;
    final match = _fileNamePattern.firstMatch(fileName);
    if (entity is File && match != null) {
      files.add((version: int.parse(match.group(1)!), name: match.group(2)!, fileName: fileName));
    }
  }
  return files..sort((a, b) => a.version.compareTo(b.version));
}

/// `add_currency_to_expenses` -> `AddCurrencyToExpenses`.
String _className(String name) =>
    name.split('_').where((w) => w.isNotEmpty).map((w) => w[0].toUpperCase() + w.substring(1)).join();

String _migrationTemplate(int version, String name) => '''
// The <unix time>_<name>.dart file name is intentional.
// ignore_for_file: file_names

import '../migration/migration.dart';

// TODO: Describe what this migration changes and why.
class ${_className(name)} extends Migration {
  const ${_className(name)}() : super(version: $version, name: '$name');

  @override
  Future<void> up(Migrator m) async {
    // TODO: Make the change, for example:
    // await m.addColumn('expenses', 'currency', SqliteType.text);
  }

  @override
  Future<void> down(Migrator m) async {
    // TODO: Undo exactly what up() did, for example:
    // await m.removeColumn('expenses', 'currency');
    // If it cannot be undone: throw const IrreversibleMigration();
  }
}
''';

void _writeRegistry(List<_MigrationFile> migrations) {
  migrations.sort((a, b) => a.version.compareTo(b.version));
  final buffer = StringBuffer()
    ..writeln('// GENERATED by `dart tool/new_migration.dart`. Do not edit by hand.')
    ..writeln()
    ..writeln("import '../migration/migration.dart';");
  for (final m in migrations) {
    buffer.writeln("import '${m.fileName}';");
  }
  buffer
    ..writeln()
    ..writeln('/// Every migration, oldest first.');
  if (migrations.isEmpty) {
    buffer.writeln('const List<Migration> allMigrations = [];');
  } else {
    buffer.writeln('const List<Migration> allMigrations = [');
    for (final m in migrations) {
      buffer.writeln('  ${_className(m.name)}(),');
    }
    buffer.writeln('];');
  }
  File.fromUri(_migrationsFolder.uri.resolve('all_migrations.dart')).writeAsStringSync(buffer.toString());
}

String _relative(String path) {
  final root = Directory.current.path;
  return path.startsWith(root) ? path.substring(root.length + 1) : path;
}
